// Aktif dil
let currentLang = localStorage.getItem('bbLang') || 'tr';

function t(key) { return TRANSLATIONS[currentLang][key] || TRANSLATIONS['tr'][key] || key; }

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('bbLang', lang);
  document.documentElement.lang = lang;
  applyTranslations();
  updateLangBtn();
  // Dinamik içerikleri yeniden yükle (villa kartları, yorumlar, vs)
  if (typeof loadVillas === 'function') loadVillas();
  if (typeof loadRegions === 'function') loadRegions();
  if (typeof loadReviews === 'function') loadReviews();
  if (typeof renderList === 'function') renderList();
  if (typeof loadAdminReviews === 'function') loadAdminReviews();
  if (typeof updateFavCount === 'function') updateFavCount();
}

function updateLangBtn() {
  const btn = document.getElementById('lang-btn');
  if (btn) btn.innerHTML = currentLang === 'tr'
    ? '<span style="font-size:16px">🇬🇧</span> EN'
    : '<span style="font-size:16px">🇹🇷</span> TR';
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') el.placeholder = val;
    else if (el.tagName === 'OPTION') el.textContent = val;
    else el.textContent = val;
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.getAttribute('data-i18n-html'));
  });
  // Placeholder'lar için ayrı atribüt
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    el.placeholder = t(key);
  });
  // Title attribute (tooltip) çevirisi
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.getAttribute('data-i18n-title'));
  });
  // Sayfa başlığı (document.title)
  const titleEl = document.querySelector('title[id="page-title"]');
  const titleKey = titleEl?.getAttribute('data-i18n-title-key');
  if (titleKey) document.title = t(titleKey);

  // SEO meta tag çevirisi
  const metaTranslations = {
    en: {
      'meta-desc': 'Discover the most beautiful holiday villas in Turkey. Bodrum, Fethiye, Cesme, Antalya and more. Villas with private pool, sea view — daily and weekly rentals.',
      'og-title': 'bizebivilla — Turkey\'s Most Beautiful Holiday Villas',
      'og-desc': 'From Bodrum to Fethiye, Cesme to Kas, find your dream holiday villa. Villas with private pool and sea view.',
    },
    tr: {
      'meta-desc': 'Türkiye\'nin en güzel kiralık villalarını keşfedin. Bodrum, Fethiye, Çeşme, Antalya ve daha fazlası. Havuzlu, deniz manzaralı, lüks villalar — günlük ve haftalık kiralama imkanı.',
      'og-title': 'bizebivilla — Türkiye\'nin En Güzel Kiralık Villaları',
      'og-desc': 'Bodrum\'dan Fethiye\'ye, Çeşme\'den Kaş\'a hayalinizdeki kiralık villayı bulun. Havuzlu, deniz manzaralı, lüks villalar.',
    }
  };
  Object.entries(metaTranslations[currentLang] || {}).forEach(([id, val]) => {
    const el = document.getElementById(id);
    if (el) el.setAttribute('content', val);
  });
}

// Dil butonunu oluştur ve nav'a ekle
function initLangBtn() {
  const existing = document.getElementById('lang-btn');
  if (existing) return;
  const btn = document.createElement('button');
  btn.id = 'lang-btn';
  btn.style.cssText = 'display:flex;align-items:center;gap:6px;padding:7px 14px;border:1px solid var(--border,#eee);border-radius:7px;font-size:13px;font-weight:500;cursor:pointer;background:#fff;font-family:DM Sans,sans-serif;transition:all 0.2s';
  btn.onclick = () => setLang(currentLang === 'tr' ? 'en' : 'tr');
  btn.innerHTML = currentLang === 'tr' ? '<span style="font-size:16px">🇬🇧</span> EN' : '<span style="font-size:16px">🇹🇷</span> TR';
  btn.onmouseover = () => btn.style.background = '#f5f5f5';
  btn.onmouseout  = () => btn.style.background = '#fff';

  // Nav'ın link listesinin sonuna ekle
  const navLinks = document.querySelector('.nav-links');
  if (navLinks) navLinks.insertBefore(btn, navLinks.lastElementChild);

  document.documentElement.lang = currentLang;
  applyTranslations();
}

// Sayfa yüklenir yüklenmez nav'ı çevir (header TR kalmasını önle)
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initLangBtn);
  // Aynı zamanda DOM hazır olur olmaz applyTranslations'ı da çalıştır
  document.addEventListener('readystatechange', () => {
    if (document.readyState !== 'loading') applyTranslations();
  });
} else {
  initLangBtn();
}

// MutationObserver — sadece YENİ eklenen elementleri çevir, sonsuz döngüye girme
let i18nApplying = false;
function safeApply() {
  if (i18nApplying) return;
  i18nApplying = true;
  applyTranslations();
  // Mikro-task sonrası flag'i bırak
  Promise.resolve().then(() => { i18nApplying = false; });
}

function startObserver() {
  if (!document.body) return;
  const observer = new MutationObserver((mutations) => {
    if (i18nApplying) return;
    // Sadece yeni node eklendiyse ve içinde data-i18n varsa çevir
    let needsApply = false;
    for (const m of mutations) {
      for (const node of m.addedNodes) {
        if (node.nodeType === 1 && (
          node.hasAttribute?.('data-i18n') ||
          node.hasAttribute?.('data-i18n-html') ||
          node.hasAttribute?.('data-i18n-ph') ||
          node.querySelector?.('[data-i18n], [data-i18n-html], [data-i18n-ph]')
        )) {
          needsApply = true; break;
        }
      }
      if (needsApply) break;
    }
    if (needsApply) safeApply();
  });
  observer.observe(document.body, { childList: true, subtree: true });
}

if (document.body) startObserver();
else document.addEventListener('DOMContentLoaded', startObserver);
